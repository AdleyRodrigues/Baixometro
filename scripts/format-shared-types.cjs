const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'packages', 'shared-types');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'index.ts');

for (const file of files) {
  const filePath = path.join(dir, file);
  let content = fs.readFileSync(filePath, 'utf-8');

  // Remove ts-rs header
  content = content.replace(/\/\/ This file was generated by \[ts-rs\][^\r\n]*\r?\n?/g, '');
  content = content.trim();

  // Match export type Name = { ... };
  const typeMatch = content.match(/^(.*?)export type\s+(\w+)\s*=\s*\{\s*(.*?)\s*\};?$/s);
  if (!typeMatch) {
    console.log(`Skipping ${file}: does not match pattern`);
    continue;
  }

  const prefix = typeMatch[1].trim(); // imports or comments before export type
  const typeName = typeMatch[2];
  const body = typeMatch[3];

  const fieldRegex = /(?:(\/\*\*[\s\S]*?\*\/)\s*)?([a-zA-Z0-9_]+(?:\?)?\s*:\s*[^,;]+)[,;]?/g;
  let match;
  const fields = [];
  while ((match = fieldRegex.exec(body)) !== null) {
    const doc = match[1] ? match[1].trim() : null;
    let prop = match[2].trim();
    if (prop.endsWith(',')) prop = prop.slice(0, -1).trim();
    if (prop.endsWith(';')) prop = prop.slice(0, -1).trim();
    fields.push({ doc, prop });
  }

  let formatted = '';
  if (prefix) {
    formatted += prefix + '\n\n';
  }
  formatted += `export type ${typeName} = {\n`;
  for (const { doc, prop } of fields) {
    if (doc) {
      const docLines = doc.split(/\r?\n/).map(l => {
        const trimmed = l.trim();
        return trimmed.startsWith('*') ? ' ' + trimmed : trimmed;
      }).map(l => '  ' + l).join('\n');
      formatted += docLines + '\n';
    }
    formatted += `  ${prop},\n`;
  }
  formatted += `};\n`;

  fs.writeFileSync(filePath, formatted, 'utf-8');
}
console.log('All shared-types formatted successfully.');
